// Builds src/convex/api.ts from convex-spec/live-function-spec.json.
//
// Why: the live Convex deployment is ahead of the convex/ folder in GitHub
// (see farmkeke-docs/pending-backend/README.md). Until the real source is
// committed, the website types its calls from the deployed function spec.
// Argument types are exact; return types are not in the spec, so each area
// declares the shapes it reads in src/convex/returns/*.ts.
//
// Refresh the spec (read-only) from the repo root, then regenerate:
//   npx convex function-spec > web/convex-spec/live-function-spec.json
//   npm --prefix web run gen:api
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const spec = JSON.parse(fs.readFileSync(path.join(root, "convex-spec/live-function-spec.json"), "utf8"));

const type = (v) => {
  if (!v) return "unknown";
  switch (v.type) {
    case "string":
    case "number":
    case "boolean":
    case "null":
      return v.type;
    case "any":
      return "unknown";
    case "bigint":
      return "bigint";
    case "bytes":
      return "ArrayBuffer";
    case "literal":
      return JSON.stringify(v.value);
    case "id":
      return `Id<${JSON.stringify(v.tableName)}>`;
    case "array":
      return `Array<${type(v.value)}>`;
    case "union":
      return v.value.map(type).join(" | ");
    case "record":
      return `Record<${type(v.keys)}, ${type(v.values?.fieldType ?? v.values)}>`;
    case "object": {
      const fields = Object.entries(v.value).map(
        ([k, f]) => `${JSON.stringify(k)}${f.optional ? "?" : ""}: ${type(f.fieldType)}`,
      );
      return fields.length ? `{ ${fields.join("; ")} }` : "Record<string, never>";
    }
    default:
      return "unknown";
  }
};

const kinds = { Query: "query", Mutation: "mutation", Action: "action" };
const tree = {};
for (const f of spec.functions) {
  if (!f.identifier || f.visibility?.kind !== "public") continue;
  const [file, name] = f.identifier.split(":");
  // Staff-only functions belong to the Admin Portal, never the website.
  if (file.startsWith("admin/")) continue;
  const segments = file.replace(/\.js$/, "").split("/");
  let node = tree;
  for (const s of segments) node = node[s] ??= {};
  node[name] = { kind: kinds[f.functionType], ref: `${segments.join("/")}:${name}`, args: type(f.args) };
}

const render = (node, indent) => {
  const pad = "  ".repeat(indent);
  return Object.keys(node)
    .sort()
    .map((key) => {
      const v = node[key];
      if (v.kind) {
        return `${pad}${key}: makeFunctionReference<"${v.kind}", ${v.args}, any>(${JSON.stringify(v.ref)}),`;
      }
      return `${pad}${key}: {\n${render(v, indent + 1)}\n${pad}},`;
    })
    .join("\n");
};

const out = `/* eslint-disable */
// GENERATED by scripts/gen-convex-api.mjs from convex-spec/live-function-spec.json.
// Do not edit by hand. Return types are \`any\` here: read them through the
// typed helpers in src/convex/returns/*.ts.
import { makeFunctionReference } from "convex/server";
import type { GenericId } from "convex/values";

export type Id<T extends string> = GenericId<T>;

export const api = {
${render(tree, 1)}
} as const;
`;

fs.writeFileSync(path.join(root, "src/convex/api.ts"), out);
console.log("wrote src/convex/api.ts");
