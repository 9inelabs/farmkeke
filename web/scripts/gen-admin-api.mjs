// Builds src/convex/admin.ts (the Admin Portal's typed function references)
// from convex-spec/admin-function-spec.json, which is written from the
// convex/ code itself, so the portal can call functions before they're
// deployed. Return types are declared in src/convex/returns/admin/*.ts.
//
// After changing convex/admin/*, from the repo root:
//   node scripts/local-spec.mjs --only admin/ > web/convex-spec/admin-function-spec.json
//   npm --prefix web run gen:admin
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const spec = JSON.parse(fs.readFileSync(path.join(root, "convex-spec/admin-function-spec.json"), "utf8"));

const type = (v) => {
  if (!v) return "unknown";
  switch (v.type) {
    case "string":
    case "number":
    case "boolean":
    case "null":
      return v.type;
    case "any":
      return "unknown";
    case "bigint":
      return "bigint";
    case "bytes":
      return "ArrayBuffer";
    case "literal":
      return JSON.stringify(v.value);
    case "id":
      return `Id<${JSON.stringify(v.tableName)}>`;
    case "array":
      return `Array<${type(v.value)}>`;
    case "union":
      return v.value.map(type).join(" | ");
    case "record":
      return `Record<${type(v.keys)}, ${type(v.values?.fieldType ?? v.values)}>`;
    case "object": {
      const fields = Object.entries(v.value).map(
        ([k, f]) => `${JSON.stringify(k)}${f.optional ? "?" : ""}: ${type(f.fieldType)}`,
      );
      return fields.length ? `{ ${fields.join("; ")} }` : "Record<string, never>";
    }
    default:
      return "unknown";
  }
};

const kinds = { Query: "query", Mutation: "mutation", Action: "action" };
const tree = {};
for (const f of spec.functions) {
  if (!f.identifier || f.visibility?.kind !== "public") continue;
  const [file, name] = f.identifier.split(":");
  if (!file.startsWith("admin/")) continue;
  const segments = file.replace(/\.js$/, "").split("/").slice(1);
  let node = tree;
  for (const s of segments) node = node[s] ??= {};
  node[name] = { kind: kinds[f.functionType], ref: `admin/${segments.join("/")}:${name}`, args: type(f.args) };
}

const render = (node, indent) => {
  const pad = "  ".repeat(indent);
  return Object.keys(node)
    .sort()
    .map((key) => {
      const v = node[key];
      if (v.kind) {
        return `${pad}${key}: makeFunctionReference<"${v.kind}", ${v.args}, any>(${JSON.stringify(v.ref)}),`;
      }
      return `${pad}${key}: {\n${render(v, indent + 1)}\n${pad}},`;
    })
    .join("\n");
};

const out = `// GENERATED by scripts/gen-admin-api.mjs from convex-spec/admin-function-spec.json. Do not edit.
// The Admin Portal's Convex functions (convex/admin/*). Staff-only: every one
// checks the caller's permissions on the server.
/* eslint-disable */
import { makeFunctionReference } from "convex/server";
import type { Id } from "./api";

export const admin = {
${render(tree, 1)}
} as const;
`;
fs.writeFileSync(path.join(root, "src/convex/admin.ts"), out);
console.log("wrote src/convex/admin.ts");
