// Writes modules.ts: the repo's convex/ files as a convex-test module map.
// Run automatically by `npm test`.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../convex");
const files = [];
const walk = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) walk(full);
    else if (/\.(ts|js)$/.test(e.name) && !e.name.endsWith(".d.ts")) files.push(full);
  }
};
walk(root);
const rel = (f) => path.relative(root, f).split(path.sep).join("/");
const lines = files.map((f) => `  ${JSON.stringify("/convex/" + rel(f))}: () => import(${JSON.stringify("../convex/" + rel(f))}),`);
fs.writeFileSync(
  path.join(here, "modules.ts"),
  `// GENERATED by genmodules.mjs. Do not edit.\nexport const modules: Record<string, () => Promise<any>> = {\n${lines.join("\n")}\n};\n`,
);
console.log(files.length, "modules");
